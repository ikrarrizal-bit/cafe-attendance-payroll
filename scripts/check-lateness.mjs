import assert from 'node:assert/strict';
import {attendanceLateness,formatLateMinutes,latenessTotals} from '../lib/lateness.ts';
import {attendanceReport,tally} from '../lib/payroll.ts';
const record={id:'a',employee:'one',day:'2026-10-17',clockIn:'2026-10-17T07:10:00+07:00',clockOut:'2026-10-17T15:00:00+07:00',basis:'daily',rate:100000};
const schedule={start:'07:00',end:'15:00'};
const pause={startedAt:'2026-10-17T10:00:00+07:00',resumedAt:'2026-10-17T11:40:00+07:00'};
const result=attendanceLateness(record,schedule,pause);
assert.equal(result.checkInMinutes,5);assert.equal(result.breakMinutes,10);assert.equal(result.totalMinutes,15);
assert.equal(attendanceLateness({...record,clockIn:'2026-10-17T07:05:00+07:00'},schedule,null).checkInMinutes,0);
assert.equal(attendanceLateness(record,schedule,{...pause,resumedAt:'2026-10-17T11:30:00+07:00'}).breakMinutes,0);
assert.equal(attendanceLateness(record,schedule,{...pause,resumedAt:'2026-10-17T12:00:00+07:00'}).breakMinutes,30);
assert.equal(attendanceLateness(record,null,pause).checkInMinutes,null);
assert.equal(attendanceLateness(record,schedule,{startedAt:pause.startedAt},Date.parse(pause.resumedAt)).breakActive,true);
assert.equal(formatLateMinutes(65),'1 h 5 min');assert.equal(formatLateMinutes(null),'Not recorded');
const settings={'attendanceSchedule:a':JSON.stringify(schedule),'break:a':JSON.stringify(pause)};
const employee={id:'one',start:'2026-10-17'};
const report=attendanceReport(employee,[record],employee.start,settings,'2026-10-17');
assert.equal(report[0].lateness.totalMinutes,15);
assert.equal(latenessTotals(report).totalMinutes,15);
assert.equal(latenessTotals([{record,lateness:undefined}]).notRecorded,1);
assert.equal(tally(employee,[record],[],settings).amount,100000,'Lateness does not reduce salary');
console.log('Lateness checks passed: check-in grace, 90-minute break threshold, combined totals, unknown schedules, provisional breaks and unchanged salary.');
